"use client";

import { useEffect, useState } from "react";
import { ArrowUp } from "lucide-react";
import { cn } from "@/lib/utils";

export function BackToTop() {
  const [show, setShow] = useState(false);

  useEffect(() => {
    const onScroll = () => setShow(window.scrollY > 800);
    onScroll();
    window.addEventListener("scroll", onScroll, { passive: true });
    return () => window.removeEventListener("scroll", onScroll);
  }, []);

  return (
    <button
      type="button"
      onClick={() => window.scrollTo({ top: 0, behavior: "smooth" })}
      aria-label="Back to top"
      className={cn(
        // Desktop-only — on mobile, users scroll naturally and the sticky bar handles CTAs
        "fixed left-6 bottom-6 z-40 hidden h-11 w-11 place-items-center rounded-full border border-border bg-card/95 text-foreground shadow-lg backdrop-blur transition-all duration-300 hover:border-primary/40 hover:text-primary hover:shadow-xl lg:grid",
        show ? "translate-y-0 opacity-100" : "pointer-events-none translate-y-4 opacity-0"
      )}
    >
      <ArrowUp className="h-5 w-5" />
    </button>
  );
}
